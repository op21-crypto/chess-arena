/**
 * Returns a randomized cool anime opponent tailored to the requested difficulty level.
 * @param {number} level - Stockfish difficulty tier (1 - 5)
 * @returns {object} Anime opponent data
 */
export function getRandomAnimeOpponent(level = 2) {
  const safeLevel = Math.max(1, Math.min(5, Math.floor(Number(level) || 2)));
  const roster = ANIME_AI_ROSTER[safeLevel] || ANIME_AI_ROSTER[2];
  const randomIndex = Math.floor(Math.random() * roster.length);
  const chosen = roster[randomIndex];

  return {
    ...chosen,
    // Add dynamic seed timestamp to ensure fresh avatar URL rendering
    avatar: chosen.avatar || `https://api.dicebear.com/7.x/adventurer/svg?seed=${encodeURIComponent(chosen.username)}&radius=50`
  };
}
